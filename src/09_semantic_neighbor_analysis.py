class SemanticNeighborAnalysisError(RuntimeError):
    """Raised when semantic-neighbour analysis cannot be completed safely."""


@dataclass(frozen=True)
class NeighborSettings:
    """Resolved configuration for semantic-neighbour analysis."""

    neighbor_count: int
    n_jobs: int
    figure_dpi: int
    top_classes: int


