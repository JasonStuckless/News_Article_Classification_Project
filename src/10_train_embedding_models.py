"""
10_train_embedding_models.py

Train supervised classifiers using the Sentence-BERT embeddings generated by
08_generate_sentence_embeddings.py.

This stage integrates the embedding-based classification methodology developed
in the project notebook. The notebook's five classifiers are retained:

- Logistic Regression
- Linear Support Vector Machine
- Random Forest
- XGBoost
- Small Neural Network

Each classifier is trained under four experimental conditions:

1. Category prediction using original CNN labels.
2. Category prediction using LLM-generated labels.
3. Section prediction using original CNN labels.
4. Section prediction using LLM-generated labels.

The Sentence-BERT embedding matrix is shared across all conditions. Only the
training labels change. A condition-specific LabelEncoder is stored with every
trained model so that non-contiguous or rare Section labels do not prevent
training and later evaluation.

Inputs:
- data/interim/train_original.csv
- data/interim/train_llm_labeled.csv
- data/processed/sentence_embeddings/train_embeddings.npy
- data/processed/sentence_embeddings/train_metadata.csv
- data/processed/sentence_embeddings/embedding_manifest.json

Outputs:
- models/sentence_bert/category/real/*.pkl
- models/sentence_bert/category/llm/*.pkl
- models/sentence_bert/section/real/*.pkl
- models/sentence_bert/section/llm/*.pkl
- results/tables/sentence_bert/embedding_model_training_summary.csv
- models/sentence_bert/training_manifest.json
"""

