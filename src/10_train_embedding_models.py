def load_training_dataset(file_path: Path, dataset_name: str) -> pd.DataFrame:
    """Load and validate one training dataset."""
    if not file_path.exists():
        raise EmbeddingModelTrainingError(
            f"{dataset_name} not found: {file_path}"
        )

    dataframe = read_csv(file_path)
    if dataframe.empty:
        raise EmbeddingModelTrainingError(
            f"{dataset_name} contains no rows."
        )

    required_columns = {ID_COLUMN, CATEGORY_COLUMN, SECTION_COLUMN}
    missing_columns = required_columns - set(dataframe.columns)
    if missing_columns:
        missing = ", ".join(sorted(missing_columns))
        raise EmbeddingModelTrainingError(
            f"{dataset_name} is missing required columns: {missing}"
        )

    if dataframe[ID_COLUMN].isna().any():
        raise EmbeddingModelTrainingError(
            f"{dataset_name} contains missing {ID_COLUMN} values."
        )
    if not dataframe[ID_COLUMN].is_unique:
        raise EmbeddingModelTrainingError(
            f"{dataset_name} contains duplicated {ID_COLUMN} values."
        )

    for column in (CATEGORY_COLUMN, SECTION_COLUMN):
        labels = dataframe[column]
        if labels.isna().any():
            raise EmbeddingModelTrainingError(
                f"{dataset_name} contains missing {column} labels."
            )
        if labels.astype(str).str.strip().eq("").any():
            raise EmbeddingModelTrainingError(
                f"{dataset_name} contains blank {column} labels."
            )

    logger.info("Loaded %s: %d rows.", dataset_name, len(dataframe))
    return dataframe


def validate_training_alignment(
    original_training: pd.DataFrame,
    llm_training: pd.DataFrame,
) -> None:
    """Verify that label source is the only difference between datasets."""
    if list(original_training.columns) != list(llm_training.columns):
        raise EmbeddingModelTrainingError(
            "The original-label and LLM-label datasets have different columns "
            "or column order."
        )
    if len(original_training) != len(llm_training):
        raise EmbeddingModelTrainingError(
            "The original-label and LLM-label datasets have different row counts."
        )
    if list(original_training[ID_COLUMN]) != list(llm_training[ID_COLUMN]):
        raise EmbeddingModelTrainingError(
            "The original-label and LLM-label datasets are not in the same row order."
        )

    non_label_columns = [
        column
        for column in original_training.columns
        if column not in {CATEGORY_COLUMN, SECTION_COLUMN}
    ]

    try:
        pd.testing.assert_frame_equal(
            original_training[non_label_columns].reset_index(drop=True),
            llm_training[non_label_columns].reset_index(drop=True),
            check_dtype=False,
            check_like=False,
        )
    except AssertionError as error:
        raise EmbeddingModelTrainingError(
            "The training datasets differ in one or more non-label values."
        ) from error

    logger.info("Original-label and LLM-label training datasets are aligned.")


def load_embeddings(expected_rows: int) -> np.ndarray:
    """Load and validate the training Sentence-BERT matrix."""
    if not TRAIN_EMBEDDINGS_PATH.exists():
        raise EmbeddingModelTrainingError(
            "Training embeddings were not found. Run "
            "08_generate_sentence_embeddings.py first: "
            f"{TRAIN_EMBEDDINGS_PATH}"
        )

    try:
        embeddings = np.load(TRAIN_EMBEDDINGS_PATH, allow_pickle=False)
    except (OSError, ValueError) as error:
        raise EmbeddingModelTrainingError(
            f"Could not load training embeddings: {error}"
        ) from error

    if embeddings.ndim != 2:
        raise EmbeddingModelTrainingError(
            "Training embeddings must be a two-dimensional matrix."
        )
    if embeddings.shape[0] != expected_rows:
        raise EmbeddingModelTrainingError(
            "Embedding row count does not match the training datasets. "
            f"Embeddings: {embeddings.shape[0]}; rows: {expected_rows}."
        )
    if embeddings.shape[1] <= 0:
        raise EmbeddingModelTrainingError(
            "Training embeddings contain no features."
        )
    if not np.issubdtype(embeddings.dtype, np.number):
        raise EmbeddingModelTrainingError(
            "Training embeddings must contain numeric values."
        )
    if not np.isfinite(embeddings).all():
        raise EmbeddingModelTrainingError(
            "Training embeddings contain NaN or infinite values."
        )

    logger.info(
        "Loaded training embeddings: %d rows and %d dimensions.",
        embeddings.shape[0],
        embeddings.shape[1],
    )
    return np.asarray(embeddings, dtype=np.float32)


def validate_embedding_metadata(training: pd.DataFrame) -> None:
    """Confirm that embedding rows align with dataset rows."""
    if not TRAIN_METADATA_PATH.exists():
        raise EmbeddingModelTrainingError(
            "Embedding metadata was not found. Run "
            "08_generate_sentence_embeddings.py first: "
            f"{TRAIN_METADATA_PATH}"
        )

    metadata = read_csv(TRAIN_METADATA_PATH)
    required_columns = {ID_COLUMN, "embedding_row"}
    missing_columns = required_columns - set(metadata.columns)
    if missing_columns:
        missing = ", ".join(sorted(missing_columns))
        raise EmbeddingModelTrainingError(
            f"Embedding metadata is missing columns: {missing}"
        )

    if len(metadata) != len(training):
        raise EmbeddingModelTrainingError(
            "Embedding metadata row count does not match the training dataset."
        )

    expected_rows = np.arange(len(metadata), dtype=int)
    actual_rows = pd.to_numeric(
        metadata["embedding_row"], errors="coerce"
    ).to_numpy()
    if np.isnan(actual_rows).any() or not np.array_equal(
        actual_rows.astype(int), expected_rows
    ):
        raise EmbeddingModelTrainingError(
            "Embedding metadata has invalid or reordered embedding_row values."
        )

    if list(metadata[ID_COLUMN].astype(str)) != list(
        training[ID_COLUMN].astype(str)
    ):
        raise EmbeddingModelTrainingError(
            "Embedding metadata does not align with the training dataset IDs."
        )

    logger.info("Embedding metadata is aligned with the training dataset.")


def load_embedding_manifest() -> dict[str, Any]:
    """Load the embedding-stage manifest when available."""
    if not EMBEDDING_MANIFEST_PATH.exists():
        logger.warning(
            "Embedding manifest not found; model training will continue after "
            "matrix and metadata validation."
        )
        return {}

    try:
        with EMBEDDING_MANIFEST_PATH.open("r", encoding="utf-8") as file:
            manifest = json.load(file)
    except (OSError, json.JSONDecodeError) as error:
        raise EmbeddingModelTrainingError(
            f"Could not read the embedding manifest: {error}"
        ) from error

    if not isinstance(manifest, dict):
        raise EmbeddingModelTrainingError(
            "The embedding manifest must contain a JSON object."
        )
    return manifest


