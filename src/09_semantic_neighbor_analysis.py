def compute_neighbors(
    embeddings: np.ndarray,
    neighbor_count: int,
    n_jobs: int,
) -> tuple[np.ndarray, np.ndarray]:
    """Find each article's nearest non-self neighbours by cosine distance."""
    row_count = embeddings.shape[0]
    if row_count < 2:
        raise SemanticNeighborAnalysisError(
            "At least two articles are required for nearest-neighbour analysis."
        )

    effective_count = min(neighbor_count, row_count - 1)
    if effective_count != neighbor_count:
        logger.warning(
            "Requested %d neighbours but only %d are available; using %d.",
            neighbor_count,
            row_count - 1,
            effective_count,
        )

    model = NearestNeighbors(
        n_neighbors=effective_count + 1,
        metric="cosine",
        n_jobs=n_jobs,
    )
    model.fit(embeddings)
    distances, indices = model.kneighbors(embeddings)

    # The first returned index is normally the query row itself. Remove self by
    # identity rather than assuming its position, then retain the requested count.
    neighbor_indices = np.empty((row_count, effective_count), dtype=int)
    neighbor_similarities = np.empty(
        (row_count, effective_count), dtype=np.float32
    )

    for row_index in range(row_count):
        candidates = [
            (int(index), float(distance))
            for index, distance in zip(indices[row_index], distances[row_index])
            if int(index) != row_index
        ]
        if len(candidates) < effective_count:
            raise SemanticNeighborAnalysisError(
                "Nearest-neighbour retrieval did not return enough non-self rows."
            )
        selected = candidates[:effective_count]
        neighbor_indices[row_index] = [item[0] for item in selected]
        neighbor_similarities[row_index] = [1.0 - item[1] for item in selected]

    return neighbor_indices, neighbor_similarities


def create_article_results(
    metadata: pd.DataFrame,
    neighbor_indices: np.ndarray,
    neighbor_similarities: np.ndarray,
    label_mapping: dict[str, str],
) -> pd.DataFrame:
    """Create one wide result row per article, matching the notebook format."""
    results = metadata[[ID_COLUMN, HEADLINE_COLUMN]].copy()

    for output_label in label_mapping:
        results[output_label] = metadata[label_mapping[output_label]].to_numpy()

    for rank in range(neighbor_indices.shape[1]):
        rank_number = rank + 1
        selected_indices = neighbor_indices[:, rank]
        results[f"neighbor_{rank_number}_index"] = metadata.iloc[
            selected_indices
        ][ID_COLUMN].to_numpy()
        results[f"neighbor_{rank_number}_headline"] = metadata.iloc[
            selected_indices
        ][HEADLINE_COLUMN].to_numpy()
        results[f"neighbor_{rank_number}_similarity"] = (
            neighbor_similarities[:, rank]
        )

    for output_label in label_mapping:
        source_column = label_mapping[output_label]
        labels = metadata[source_column].astype(str).to_numpy()
        same_label = labels[neighbor_indices] == labels[:, None]
        results[f"same_{output_label}_neighbor_ratio"] = same_label.mean(axis=1)

    results["mean_neighbor_similarity"] = neighbor_similarities.mean(axis=1)
    results["minimum_neighbor_similarity"] = neighbor_similarities.min(axis=1)
    results["maximum_neighbor_similarity"] = neighbor_similarities.max(axis=1)
    return results


def create_neighbor_pairs(
    metadata: pd.DataFrame,
    neighbor_indices: np.ndarray,
    neighbor_similarities: np.ndarray,
    label_mapping: dict[str, str],
    dataset_name: str,
) -> pd.DataFrame:
    """Create a long-format table containing one row per neighbour pair."""
    rows: list[dict[str, Any]] = []

    for article_row in range(len(metadata)):
        source = metadata.iloc[article_row]
        for rank, neighbor_row in enumerate(neighbor_indices[article_row], start=1):
            neighbor = metadata.iloc[int(neighbor_row)]
            row: dict[str, Any] = {
                "dataset": dataset_name,
                "article_embedding_row": article_row,
                "article_index": source[ID_COLUMN],
                "article_headline": source[HEADLINE_COLUMN],
                "neighbor_rank": rank,
                "neighbor_embedding_row": int(neighbor_row),
                "neighbor_index": neighbor[ID_COLUMN],
                "neighbor_headline": neighbor[HEADLINE_COLUMN],
                "cosine_similarity": float(
                    neighbor_similarities[article_row, rank - 1]
                ),
            }
            for output_label, source_column in label_mapping.items():
                article_label = source[source_column]
                neighbor_label = neighbor[source_column]
                row[f"article_{output_label}"] = article_label
                row[f"neighbor_{output_label}"] = neighbor_label
                row[f"same_{output_label}"] = bool(
                    str(article_label) == str(neighbor_label)
                )
            rows.append(row)

    return pd.DataFrame(rows)


def summarize_label_source(
    article_results: pd.DataFrame,
    dataset_name: str,
    label_mapping: dict[str, str],
) -> pd.DataFrame:
    """Summarize article-level agreement ratios for each label definition."""
    rows: list[dict[str, Any]] = []
    for output_label in label_mapping:
        ratio_column = f"same_{output_label}_neighbor_ratio"
        values = article_results[ratio_column]
        rows.append(
            {
                "dataset": dataset_name,
                "label_definition": output_label,
                "article_count": int(len(values)),
                "mean_neighbor_agreement": float(values.mean()),
                "median_neighbor_agreement": float(values.median()),
                "standard_deviation": float(values.std(ddof=1)),
                "minimum_neighbor_agreement": float(values.min()),
                "maximum_neighbor_agreement": float(values.max()),
                "perfect_agreement_article_ratio": float((values == 1.0).mean()),
                "zero_agreement_article_ratio": float((values == 0.0).mean()),
                "mean_cosine_similarity": float(
                    article_results["mean_neighbor_similarity"].mean()
                ),
            }
        )
    return pd.DataFrame(rows)


def summarize_by_class(
    metadata: pd.DataFrame,
    article_results: pd.DataFrame,
    label_mapping: dict[str, str],
    dataset_name: str,
) -> pd.DataFrame:
    """Aggregate neighbour consistency by label class."""
    rows: list[dict[str, Any]] = []

    for output_label, source_column in label_mapping.items():
        working = pd.DataFrame(
            {
                "label": metadata[source_column].astype(str).to_numpy(),
                "agreement": article_results[
                    f"same_{output_label}_neighbor_ratio"
                ].to_numpy(),
                "similarity": article_results[
                    "mean_neighbor_similarity"
                ].to_numpy(),
            }
        )
        for class_name, group in working.groupby("label", sort=True):
            rows.append(
                {
                    "dataset": dataset_name,
                    "label_definition": output_label,
                    "class": class_name,
                    "article_count": int(len(group)),
                    "mean_neighbor_agreement": float(group["agreement"].mean()),
                    "median_neighbor_agreement": float(
                        group["agreement"].median()
                    ),
                    "mean_cosine_similarity": float(group["similarity"].mean()),
                }
            )

    return pd.DataFrame(rows)


