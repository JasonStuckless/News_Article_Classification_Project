def run_embedding_model_training(config_path: Path = CONFIG_PATH) -> None:
    """Run all enabled Sentence-BERT model-training experiments."""
    logger.info("Starting Sentence-BERT model training.")

    config = load_config(config_path)
    dataset_config = config["dataset"]
    random_seed = int(config["project"]["random_seed"])
    np.random.seed(random_seed)

    original_training_path = resolve_project_path(
        str(dataset_config["train_file"])
    )
    llm_training_path = resolve_project_path(
        str(dataset_config["llm_train_file"])
    )

    original_training = load_training_dataset(
        original_training_path,
        "original-label training dataset",
    )
    llm_training = load_training_dataset(
        llm_training_path,
        "LLM-label training dataset",
    )
    validate_training_alignment(original_training, llm_training)
    validate_embedding_metadata(original_training)

    embeddings = load_embeddings(expected_rows=len(original_training))
    embedding_manifest = load_embedding_manifest()
    settings = get_model_settings(config)

    conditions: tuple[tuple[TrainingCondition, pd.DataFrame], ...] = (
        (
            TrainingCondition(
                target=TARGET_CATEGORY,
                label_source=LABEL_SOURCE_REAL,
                label_column=CATEGORY_COLUMN,
            ),
            original_training,
        ),
        (
            TrainingCondition(
                target=TARGET_CATEGORY,
                label_source=LABEL_SOURCE_LLM,
                label_column=CATEGORY_COLUMN,
            ),
            llm_training,
        ),
        (
            TrainingCondition(
                target=TARGET_SECTION,
                label_source=LABEL_SOURCE_REAL,
                label_column=SECTION_COLUMN,
            ),
            original_training,
        ),
        (
            TrainingCondition(
                target=TARGET_SECTION,
                label_source=LABEL_SOURCE_LLM,
                label_column=SECTION_COLUMN,
            ),
            llm_training,
        ),
    )

    summary_rows: list[dict[str, Any]] = []
    stage_start = time.perf_counter()

    for condition, dataframe in conditions:
        labels, label_encoder = prepare_labels(
            dataframe,
            condition.label_column,
        )

        class_counts = pd.Series(labels).value_counts()
        logger.info(
            "%s/%s label distribution: %d classes; minimum class count=%d; "
            "maximum class count=%d.",
            condition.target,
            condition.label_source,
            len(class_counts),
            int(class_counts.min()),
            int(class_counts.max()),
        )

        for setting in settings:
            if not setting.enabled:
                logger.info(
                    "Skipping disabled embedding classifier: %s.",
                    setting.model_name,
                )
                continue

            summary_rows.append(
                train_one_model(
                    embeddings=embeddings,
                    labels=labels,
                    label_encoder=label_encoder,
                    condition=condition,
                    setting=setting,
                    random_seed=random_seed,
                    embedding_manifest=embedding_manifest,
                )
            )

    total_elapsed = time.perf_counter() - stage_start
    summary = pd.DataFrame(summary_rows)
    if summary.empty:
        raise EmbeddingModelTrainingError(
            "No embedding models were trained."
        )

    write_csv(summary, TRAINING_SUMMARY_PATH)

    manifest = {
        "artifact_version": "1.0",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "representation": "sentence_bert",
        "random_seed": random_seed,
        "training_rows": int(embeddings.shape[0]),
        "embedding_dimension": int(embeddings.shape[1]),
        "embedding_model_name": embedding_manifest.get("model_name"),
        "total_models_trained": int(len(summary)),
        "total_training_time_seconds": total_elapsed,
        "conditions": [
            asdict(condition)
            for condition, _ in conditions
        ],
        "enabled_models": [
            {
                "model_name": setting.model_name,
                "display_name": MODEL_DISPLAY_NAMES[setting.model_name],
                "parameters": setting.parameters,
            }
            for setting in settings
            if setting.enabled
        ],
        "outputs": {
            "model_directory": str(MODEL_DIRECTORY.relative_to(PROJECT_ROOT)),
            "training_summary": str(
                TRAINING_SUMMARY_PATH.relative_to(PROJECT_ROOT)
            ),
        },
    }
    write_json_atomic(manifest, TRAINING_MANIFEST_PATH)

    logger.info(
        "Sentence-BERT model training completed: %d models in %.3f seconds.",
        len(summary),
        total_elapsed,
    )


if __name__ == "__main__":
    try:
        run_embedding_model_training()
    except EmbeddingModelTrainingError:
        logger.exception("Sentence-BERT model training failed.")
        raise
    except Exception:
        logger.exception(
            "Sentence-BERT model training failed unexpectedly."
        )
        raise
