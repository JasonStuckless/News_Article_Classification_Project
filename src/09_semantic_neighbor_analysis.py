def run_semantic_neighbor_analysis(
    config_path: Path = CONFIG_PATH,
) -> None:
    """Run the complete semantic nearest-neighbour analysis stage."""
    logger.info("Starting semantic nearest-neighbour analysis.")

    config = load_config(config_path)
    settings = get_neighbor_settings(config)
    dataset_config = config["dataset"]

    train_original_path = resolve_project_path(dataset_config["train_file"])
    train_llm_path = resolve_project_path(dataset_config["llm_train_file"])

    require_files(
        [
            FULL_EMBEDDINGS_PATH,
            TRAIN_EMBEDDINGS_PATH,
            FULL_METADATA_PATH,
            TRAIN_METADATA_PATH,
            MANIFEST_PATH,
            train_original_path,
            train_llm_path,
        ]
    )

    TABLE_DIRECTORY.mkdir(parents=True, exist_ok=True)
    FIGURE_DIRECTORY.mkdir(parents=True, exist_ok=True)

    manifest = load_manifest()
    expected_dimension = manifest.get("embedding_dimension")
    if expected_dimension is not None:
        expected_dimension = int(expected_dimension)

    full_metadata = read_csv(FULL_METADATA_PATH)
    train_metadata = read_csv(TRAIN_METADATA_PATH)
    train_original = read_csv(train_original_path)
    train_llm = read_csv(train_llm_path)

    validate_metadata(full_metadata, "full-dataset")
    validate_metadata(train_metadata, "training")

    full_embeddings = np.load(FULL_EMBEDDINGS_PATH, mmap_mode="r")
    train_embeddings = np.load(TRAIN_EMBEDDINGS_PATH, mmap_mode="r")
    validate_embeddings(
        full_embeddings,
        full_metadata,
        "full-dataset",
        expected_dimension,
    )
    validate_embeddings(
        train_embeddings,
        train_metadata,
        "training",
        expected_dimension,
    )

    logger.info(
        "Finding %d nearest neighbours for %d full-dataset articles.",
        settings.neighbor_count,
        len(full_metadata),
    )
    full_indices, full_similarities = compute_neighbors(
        full_embeddings,
        neighbor_count=settings.neighbor_count,
        n_jobs=settings.n_jobs,
    )

    full_label_mapping = {
        "category": CATEGORY_COLUMN,
        "section": SECTION_COLUMN,
    }
    full_article_results = create_article_results(
        full_metadata,
        full_indices,
        full_similarities,
        full_label_mapping,
    )
    full_pair_results = create_neighbor_pairs(
        full_metadata,
        full_indices,
        full_similarities,
        full_label_mapping,
        dataset_name="full_original",
    )
    full_summary = summarize_label_source(
        full_article_results,
        dataset_name="full_original",
        label_mapping=full_label_mapping,
    )
    full_class_summary = summarize_by_class(
        full_metadata,
        full_article_results,
        full_label_mapping,
        dataset_name="full_original",
    )

    aligned_train = align_training_labels(
        train_metadata,
        train_original,
        train_llm,
    )
    # Attach aligned labels to metadata while preserving embedding-row order.
    train_analysis_metadata = train_metadata.copy()
    for column in (
        "original_category",
        "original_section",
        "llm_category",
        "llm_section",
    ):
        train_analysis_metadata[column] = aligned_train[column].to_numpy()

    logger.info(
        "Finding %d nearest neighbours for %d training articles.",
        settings.neighbor_count,
        len(train_analysis_metadata),
    )
    train_indices, train_similarities = compute_neighbors(
        train_embeddings,
        neighbor_count=settings.neighbor_count,
        n_jobs=settings.n_jobs,
    )
    train_label_mapping = {
        "original_category": "original_category",
        "llm_category": "llm_category",
        "original_section": "original_section",
        "llm_section": "llm_section",
    }
    train_article_results = create_article_results(
        train_analysis_metadata,
        train_indices,
        train_similarities,
        train_label_mapping,
    )
    train_pair_results = create_neighbor_pairs(
        train_analysis_metadata,
        train_indices,
        train_similarities,
        train_label_mapping,
        dataset_name="training_label_comparison",
    )
    train_summary = summarize_label_source(
        train_article_results,
        dataset_name="training_label_comparison",
        label_mapping=train_label_mapping,
    )
    train_class_summary = summarize_by_class(
        train_analysis_metadata,
        train_article_results,
        train_label_mapping,
        dataset_name="training_label_comparison",
    )

    combined_summary = pd.concat(
        [full_summary, train_summary],
        ignore_index=True,
    )

    write_csv(
        full_article_results,
        TABLE_DIRECTORY / "full_neighbor_results.csv",
    )
    write_csv(
        full_pair_results,
        TABLE_DIRECTORY / "full_neighbor_pairs.csv",
    )
    write_csv(
        full_class_summary,
        TABLE_DIRECTORY / "full_class_consistency.csv",
    )
    write_csv(
        train_article_results,
        TABLE_DIRECTORY / "train_neighbor_results.csv",
    )
    write_csv(
        train_pair_results,
        TABLE_DIRECTORY / "train_neighbor_pairs.csv",
    )
    write_csv(
        train_summary,
        TABLE_DIRECTORY / "train_label_source_summary.csv",
    )
    write_csv(
        train_class_summary,
        TABLE_DIRECTORY / "train_class_consistency.csv",
    )
    write_csv(
        combined_summary,
        TABLE_DIRECTORY / "semantic_neighbor_summary.csv",
    )

    plot_similarity_distribution(
        full_pair_results,
        FIGURE_DIRECTORY / "full_similarity_distribution.png",
        settings.figure_dpi,
    )
    plot_summary_agreement(
        full_summary,
        FIGURE_DIRECTORY / "full_category_section_consistency.png",
        settings.figure_dpi,
        "Semantic Neighbour Consistency for Original CNN Labels",
    )
    plot_summary_agreement(
        train_summary,
        FIGURE_DIRECTORY / "cnn_vs_llm_label_consistency.png",
        settings.figure_dpi,
        "Semantic Neighbour Consistency: CNN vs LLM Labels",
    )
    plot_agreement_distribution(
        train_article_results,
        list(train_label_mapping),
        FIGURE_DIRECTORY / "cnn_vs_llm_mean_median_consistency.png",
        settings.figure_dpi,
        "Mean and Median Same-Label Neighbour Ratios",
    )

    for label_definition in full_label_mapping:
        plot_class_consistency(
            full_class_summary,
            label_definition,
            FIGURE_DIRECTORY
            / f"full_{label_definition}_class_consistency.png",
            settings.figure_dpi,
            settings.top_classes,
        )

    for label_definition in train_label_mapping:
        plot_class_consistency(
            train_class_summary,
            label_definition,
            FIGURE_DIRECTORY
            / f"train_{label_definition}_class_consistency.png",
            settings.figure_dpi,
            settings.top_classes,
        )

    logger.info(
        "Semantic neighbour analysis completed. Tables: %s; figures: %s.",
        TABLE_DIRECTORY,
        FIGURE_DIRECTORY,
    )


