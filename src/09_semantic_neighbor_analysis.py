"""
09_semantic_neighbor_analysis.py

Analyze local semantic structure in the CNN News Articles dataset using the
Sentence-BERT embeddings generated by 08_generate_sentence_embeddings.py.

This stage preserves the nearest-neighbour method developed in the project
notebook:

- cosine-distance nearest-neighbour retrieval,
- five non-self neighbours per article,
- article-level neighbour headlines and cosine similarities,
- same-Category neighbour ratio.

The integrated pipeline extends that method by also evaluating:

- same-Section neighbour ratios,
- per-class neighbour consistency,
- similarity distributions,
- original CNN labels versus LLM-generated labels on the training set.

Inputs:
- data/processed/sentence_embeddings/full_embeddings.npy
- data/processed/sentence_embeddings/full_metadata.csv
- data/processed/sentence_embeddings/train_embeddings.npy
- data/processed/sentence_embeddings/train_metadata.csv
- data/processed/sentence_embeddings/embedding_manifest.json
- data/interim/train_original.csv
- data/interim/train_llm_labeled.csv

Outputs:
- results/tables/semantic_neighbors/full_neighbor_results.csv
- results/tables/semantic_neighbors/full_neighbor_pairs.csv
- results/tables/semantic_neighbors/full_class_consistency.csv
- results/tables/semantic_neighbors/train_label_source_summary.csv
- results/tables/semantic_neighbors/train_class_consistency.csv
- results/tables/semantic_neighbors/semantic_neighbor_summary.csv
- results/figures/semantic_neighbors/*.png

The script is read-only with respect to all existing datasets and embedding
artifacts.
"""

