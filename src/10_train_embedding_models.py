class EmbeddingModelTrainingError(RuntimeError):
    """Raised when embedding-based models cannot be trained safely."""


@dataclass(frozen=True)
class TrainingCondition:
    """One target and label-source combination."""

    target: str
    label_source: str
    label_column: str


@dataclass(frozen=True)
class ModelSettings:
    """Resolved configuration for one classifier."""

    model_name: str
    enabled: bool
    parameters: dict[str, Any]


