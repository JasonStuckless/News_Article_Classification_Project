def require_files(paths: Iterable[Path]) -> None:
    """Require every input artifact before starting analysis."""
    missing = [str(path) for path in paths if not path.exists()]
    if missing:
        raise SemanticNeighborAnalysisError(
            "Required semantic-analysis inputs are missing:\n- "
            + "\n- ".join(missing)
            + "\nRun 08_generate_sentence_embeddings.py first."
        )


def load_manifest() -> dict[str, Any]:
    """Load and validate the embedding manifest."""
    try:
        manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise SemanticNeighborAnalysisError(
            f"Could not read the embedding manifest: {error}"
        ) from error

    if not isinstance(manifest, dict):
        raise SemanticNeighborAnalysisError(
            "The embedding manifest must contain a JSON object."
        )
    return manifest


def validate_metadata(metadata: pd.DataFrame, dataset_name: str) -> None:
    """Validate metadata required for semantic-neighbour reporting."""
    required_columns = {
        ID_COLUMN,
        "embedding_row",
        HEADLINE_COLUMN,
        CATEGORY_COLUMN,
        SECTION_COLUMN,
    }
    missing_columns = required_columns - set(metadata.columns)
    if missing_columns:
        missing = ", ".join(sorted(missing_columns))
        raise SemanticNeighborAnalysisError(
            f"The {dataset_name} metadata is missing columns: {missing}"
        )

    if metadata.empty:
        raise SemanticNeighborAnalysisError(
            f"The {dataset_name} metadata contains no rows."
        )
    if metadata[ID_COLUMN].duplicated().any():
        raise SemanticNeighborAnalysisError(
            f"The {dataset_name} metadata contains duplicate {ID_COLUMN} values."
        )

    expected_rows = np.arange(len(metadata))
    actual_rows = metadata["embedding_row"].to_numpy()
    if not np.array_equal(actual_rows, expected_rows):
        raise SemanticNeighborAnalysisError(
            f"The {dataset_name} metadata is not in embedding-row order."
        )

    for label_column in LABEL_COLUMNS:
        if metadata[label_column].isna().any():
            raise SemanticNeighborAnalysisError(
                f"The {dataset_name} metadata contains missing {label_column} labels."
            )


def validate_embeddings(
    embeddings: np.ndarray,
    metadata: pd.DataFrame,
    dataset_name: str,
    expected_dimension: int | None,
) -> None:
    """Validate matrix shape, values, and row alignment."""
    if embeddings.ndim != 2:
        raise SemanticNeighborAnalysisError(
            f"The {dataset_name} embeddings must be a two-dimensional matrix."
        )
    if embeddings.shape[0] != len(metadata):
        raise SemanticNeighborAnalysisError(
            f"The {dataset_name} embedding and metadata row counts differ."
        )
    if expected_dimension is not None and embeddings.shape[1] != expected_dimension:
        raise SemanticNeighborAnalysisError(
            f"The {dataset_name} embedding dimension does not match the manifest."
        )
    if not np.isfinite(embeddings).all():
        raise SemanticNeighborAnalysisError(
            f"The {dataset_name} embeddings contain non-finite values."
        )


def align_training_labels(
    train_metadata: pd.DataFrame,
    train_original: pd.DataFrame,
    train_llm: pd.DataFrame,
) -> pd.DataFrame:
    """Return row-aligned original and LLM labels for training articles."""
    required_columns = {ID_COLUMN, CATEGORY_COLUMN, SECTION_COLUMN}
    for dataframe, name in (
        (train_original, "original training dataset"),
        (train_llm, "LLM-labelled training dataset"),
    ):
        missing = required_columns - set(dataframe.columns)
        if missing:
            raise SemanticNeighborAnalysisError(
                f"The {name} is missing columns: {', '.join(sorted(missing))}"
            )
        if dataframe[ID_COLUMN].duplicated().any():
            raise SemanticNeighborAnalysisError(
                f"The {name} contains duplicate {ID_COLUMN} values."
            )

    original_labels = train_original[
        [ID_COLUMN, CATEGORY_COLUMN, SECTION_COLUMN]
    ].rename(
        columns={
            CATEGORY_COLUMN: "original_category",
            SECTION_COLUMN: "original_section",
        }
    )
    llm_labels = train_llm[
        [ID_COLUMN, CATEGORY_COLUMN, SECTION_COLUMN]
    ].rename(
        columns={
            CATEGORY_COLUMN: "llm_category",
            SECTION_COLUMN: "llm_section",
        }
    )

    aligned = train_metadata[[ID_COLUMN, "embedding_row", HEADLINE_COLUMN]].merge(
        original_labels,
        on=ID_COLUMN,
        how="left",
        validate="one_to_one",
    ).merge(
        llm_labels,
        on=ID_COLUMN,
        how="left",
        validate="one_to_one",
    )

    label_columns = [
        "original_category",
        "original_section",
        "llm_category",
        "llm_section",
    ]
    if aligned[label_columns].isna().any().any():
        raise SemanticNeighborAnalysisError(
            "Could not align all original and LLM training labels to embeddings."
        )
    return aligned


