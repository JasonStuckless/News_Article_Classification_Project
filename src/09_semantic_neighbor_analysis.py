def save_figure(path: Path, dpi: int) -> None:
    """Save and close the active figure."""
    path.parent.mkdir(parents=True, exist_ok=True)
    plt.tight_layout()
    plt.savefig(path, dpi=dpi, bbox_inches="tight")
    plt.close()
    logger.info("Saved figure: %s", path)


def plot_similarity_distribution(
    pair_results: pd.DataFrame,
    output_path: Path,
    dpi: int,
) -> None:
    """Visualize cosine similarity across all retrieved neighbour pairs."""
    plt.figure(figsize=(10, 6))
    plt.hist(pair_results["cosine_similarity"], bins=40, edgecolor="black")
    plt.xlabel("Cosine similarity")
    plt.ylabel("Neighbour-pair count")
    plt.title("Distribution of Sentence-BERT Neighbour Similarities")
    plt.grid(axis="y", alpha=0.25)
    save_figure(output_path, dpi)


def plot_summary_agreement(
    summary: pd.DataFrame,
    output_path: Path,
    dpi: int,
    title: str,
) -> None:
    """Plot mean neighbour agreement for each label definition."""
    plot_data = summary.sort_values("mean_neighbor_agreement", ascending=True)
    plt.figure(figsize=(10, max(5, 0.55 * len(plot_data) + 2)))
    bars = plt.barh(
        plot_data["label_definition"],
        plot_data["mean_neighbor_agreement"],
    )
    plt.xlim(0.0, 1.0)
    plt.xlabel("Mean same-label neighbour ratio")
    plt.ylabel("Label definition")
    plt.title(title)
    plt.grid(axis="x", alpha=0.25)
    for bar, value in zip(bars, plot_data["mean_neighbor_agreement"]):
        plt.text(
            min(float(value) + 0.015, 0.96),
            bar.get_y() + bar.get_height() / 2,
            f"{value:.3f}",
            va="center",
        )
    save_figure(output_path, dpi)


def plot_class_consistency(
    class_summary: pd.DataFrame,
    label_definition: str,
    output_path: Path,
    dpi: int,
    top_classes: int,
) -> None:
    """Plot class-level consistency, retaining the most frequent classes."""
    subset = class_summary[
        class_summary["label_definition"] == label_definition
    ].copy()
    if subset.empty:
        return

    subset = subset.nlargest(top_classes, "article_count")
    subset = subset.sort_values("mean_neighbor_agreement", ascending=True)

    plt.figure(figsize=(11, max(6, 0.38 * len(subset) + 2)))
    bars = plt.barh(subset["class"], subset["mean_neighbor_agreement"])
    plt.xlim(0.0, 1.0)
    plt.xlabel("Mean same-label neighbour ratio")
    plt.ylabel("Class")
    plt.title(
        f"Semantic Neighbour Consistency by {label_definition.replace('_', ' ').title()}"
    )
    plt.grid(axis="x", alpha=0.25)
    for bar, value, count in zip(
        bars,
        subset["mean_neighbor_agreement"],
        subset["article_count"],
    ):
        plt.text(
            min(float(value) + 0.012, 0.93),
            bar.get_y() + bar.get_height() / 2,
            f"{value:.2f} (n={int(count)})",
            va="center",
            fontsize=8,
        )
    save_figure(output_path, dpi)


def plot_agreement_distribution(
    article_results: pd.DataFrame,
    label_definitions: list[str],
    output_path: Path,
    dpi: int,
    title: str,
) -> None:
    """Plot the distribution of article-level neighbour-agreement ratios."""
    positions = np.arange(len(label_definitions))
    means = [
        article_results[f"same_{label}_neighbor_ratio"].mean()
        for label in label_definitions
    ]
    medians = [
        article_results[f"same_{label}_neighbor_ratio"].median()
        for label in label_definitions
    ]
    width = 0.38

    plt.figure(figsize=(11, 6))
    plt.bar(positions - width / 2, means, width, label="Mean")
    plt.bar(positions + width / 2, medians, width, label="Median")
    plt.xticks(
        positions,
        [label.replace("_", " ").title() for label in label_definitions],
        rotation=20,
        ha="right",
    )
    plt.ylim(0.0, 1.0)
    plt.ylabel("Same-label neighbour ratio")
    plt.xlabel("Label definition")
    plt.title(title)
    plt.legend()
    plt.grid(axis="y", alpha=0.25)
    save_figure(output_path, dpi)


