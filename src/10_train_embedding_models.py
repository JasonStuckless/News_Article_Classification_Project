def prepare_labels(
    dataframe: pd.DataFrame,
    label_column: str,
) -> tuple[np.ndarray, LabelEncoder]:
    """Encode labels contiguously for all supported classifiers."""
    labels = dataframe[label_column].astype(str).str.strip().to_numpy()
    encoder = LabelEncoder()
    encoded = encoder.fit_transform(labels)

    if len(encoder.classes_) < 2:
        raise EmbeddingModelTrainingError(
            f"{label_column} requires at least two observed classes for training."
        )

    return encoded.astype(np.int64), encoder


def model_output_path(
    target: str,
    label_source: str,
    model_name: str,
) -> Path:
    """Return the artifact path for one trained model bundle."""
    return MODEL_DIRECTORY / target / label_source / f"{model_name}.pkl"


def save_pickle_atomic(value: Any, output_path: Path) -> None:
    """Serialize a Python object through an atomic file replacement."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = output_path.with_suffix(output_path.suffix + ".tmp")

    try:
        with temporary_path.open("wb") as file:
            pickle.dump(value, file, protocol=pickle.HIGHEST_PROTOCOL)
        temporary_path.replace(output_path)
    except (OSError, pickle.PickleError) as error:
        temporary_path.unlink(missing_ok=True)
        raise EmbeddingModelTrainingError(
            f"Could not save model artifact {output_path}: {error}"
        ) from error


def train_one_model(
    embeddings: np.ndarray,
    labels: np.ndarray,
    label_encoder: LabelEncoder,
    condition: TrainingCondition,
    setting: ModelSettings,
    random_seed: int,
    embedding_manifest: dict[str, Any],
) -> dict[str, Any]:
    """Train and save one model bundle, returning a summary row."""
    classifier = build_classifier(setting, random_seed)
    output_path = model_output_path(
        condition.target,
        condition.label_source,
        setting.model_name,
    )

    logger.info(
        "Training %s for %s using %s labels (%d classes).",
        MODEL_DISPLAY_NAMES[setting.model_name],
        condition.target,
        condition.label_source,
        len(label_encoder.classes_),
    )

    start_time = time.perf_counter()
    try:
        classifier.fit(embeddings, labels)
    except Exception as error:
        raise EmbeddingModelTrainingError(
            f"Training failed for {setting.model_name}, {condition.target}, "
            f"{condition.label_source}: {error}"
        ) from error
    elapsed_seconds = time.perf_counter() - start_time

    bundle = {
        "artifact_version": "1.0",
        "representation": "sentence_bert",
        "model_name": setting.model_name,
        "model_display_name": MODEL_DISPLAY_NAMES[setting.model_name],
        "target": condition.target,
        "label_source": condition.label_source,
        "label_column": condition.label_column,
        "classifier": classifier,
        "label_encoder": label_encoder,
        "classes": [str(value) for value in label_encoder.classes_],
        "parameters": setting.parameters,
        "random_seed": random_seed,
        "training_rows": int(embeddings.shape[0]),
        "embedding_dimension": int(embeddings.shape[1]),
        "embedding_model_name": embedding_manifest.get("model_name"),
        "trained_at_utc": datetime.now(timezone.utc).isoformat(),
        "training_time_seconds": elapsed_seconds,
    }
    save_pickle_atomic(bundle, output_path)

    logger.info(
        "Saved %s in %.3f seconds: %s",
        MODEL_DISPLAY_NAMES[setting.model_name],
        elapsed_seconds,
        output_path,
    )

    return {
        "representation": "Sentence-BERT",
        "target": condition.target,
        "label_source": condition.label_source,
        "model": setting.model_name,
        "model_display_name": MODEL_DISPLAY_NAMES[setting.model_name],
        "training_rows": int(embeddings.shape[0]),
        "embedding_dimension": int(embeddings.shape[1]),
        "observed_classes": int(len(label_encoder.classes_)),
        "class_labels": " | ".join(str(value) for value in label_encoder.classes_),
        "training_time_seconds": elapsed_seconds,
        "model_path": str(output_path.relative_to(PROJECT_ROOT)),
        "status": "success",
    }


def write_json_atomic(value: dict[str, Any], output_path: Path) -> None:
    """Write a formatted JSON object atomically."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = output_path.with_suffix(output_path.suffix + ".tmp")
    try:
        with temporary_path.open("w", encoding="utf-8") as file:
            json.dump(value, file, indent=2, sort_keys=True)
            file.write("\n")
        temporary_path.replace(output_path)
    except (OSError, TypeError) as error:
        temporary_path.unlink(missing_ok=True)
        raise EmbeddingModelTrainingError(
            f"Could not save JSON output {output_path}: {error}"
        ) from error


