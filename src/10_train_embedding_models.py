def create_xgboost_classifier(
    parameters: dict,
    random_seed: int,
):
    """Create an XGBoost classifier without duplicating random_state."""

    xgboost_parameters = dict(parameters)
    xgboost_parameters.setdefault("random_state", random_seed)

    return XGBClassifier(**xgboost_parameters)


def build_classifier(
    setting: ModelSettings,
    random_seed: int,
) -> ClassifierMixin:
    """Construct a fresh classifier for one training condition."""
    parameters = dict(setting.parameters)

    # Preserve the notebook's deterministic setup unless explicitly overridden.
    parameters.setdefault("random_state", random_seed)

    constructors: dict[str, Callable[..., ClassifierMixin]] = {
        MODEL_LOGISTIC: LogisticRegression,
        MODEL_SVM: LinearSVC,
        MODEL_RANDOM_FOREST: RandomForestClassifier,
        MODEL_NEURAL_NETWORK: MLPClassifier,
    }

    try:
        if setting.model_name == MODEL_XGBOOST:
            return create_xgboost_classifier(parameters, random_seed)
        return constructors[setting.model_name](**parameters)
    except TypeError as error:
        raise EmbeddingModelTrainingError(
            f"Invalid parameters for {setting.model_name}: {error}"
        ) from error


