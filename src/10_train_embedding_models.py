def load_config(config_path: Path) -> dict[str, Any]:
    """Load and validate the project configuration."""
    if not config_path.exists():
        raise EmbeddingModelTrainingError(
            f"Configuration file not found: {config_path}"
        )

    try:
        with config_path.open("r", encoding="utf-8") as file:
            config = yaml.safe_load(file)
    except yaml.YAMLError as error:
        raise EmbeddingModelTrainingError(
            f"Could not parse the configuration file: {error}"
        ) from error

    if not isinstance(config, dict):
        raise EmbeddingModelTrainingError(
            "The configuration file must contain a YAML mapping."
        )

    dataset_config = config.get("dataset")
    project_config = config.get("project")

    if not isinstance(dataset_config, dict):
        raise EmbeddingModelTrainingError(
            "The configuration must contain a 'dataset' section."
        )

    if not isinstance(project_config, dict):
        raise EmbeddingModelTrainingError(
            "The configuration must contain a 'project' section."
        )

    required_dataset_settings = {"train_file", "llm_train_file"}
    missing_dataset_settings = required_dataset_settings - set(dataset_config)
    if missing_dataset_settings:
        missing = ", ".join(sorted(missing_dataset_settings))
        raise EmbeddingModelTrainingError(
            f"Missing dataset settings in config.yaml: {missing}"
        )

    if "random_seed" not in project_config:
        raise EmbeddingModelTrainingError(
            "Missing project.random_seed in config.yaml."
        )

    if not isinstance(project_config["random_seed"], int):
        raise EmbeddingModelTrainingError(
            "project.random_seed must be an integer."
        )

    return config


def resolve_project_path(configured_path: str) -> Path:
    """Resolve a configured path relative to the project root."""
    path = Path(configured_path)
    return path if path.is_absolute() else PROJECT_ROOT / path


def get_model_settings(config: dict[str, Any]) -> list[ModelSettings]:
    """
    Resolve embedding-classifier settings.

    The future config.yaml extension may provide an ``embedding_classifiers``
    section. Until that section is added, notebook-equivalent defaults are used,
    allowing this file to work without modifying the current configuration.
    """
    configured = config.get("embedding_classifiers", {})
    if configured is None:
        configured = {}
    if not isinstance(configured, dict):
        raise EmbeddingModelTrainingError(
            "embedding_classifiers must be a YAML mapping when provided."
        )

    resolved: list[ModelSettings] = []

    for model_name in SUPPORTED_MODELS:
        defaults = dict(DEFAULT_MODEL_SETTINGS[model_name])
        user_setting = configured.get(model_name)

        if user_setting is None:
            merged = defaults
        elif isinstance(user_setting, bool):
            merged = defaults
            merged["enabled"] = user_setting
        elif isinstance(user_setting, dict):
            merged = defaults
            merged.update(user_setting)
        else:
            raise EmbeddingModelTrainingError(
                f"embedding_classifiers.{model_name} must be a Boolean "
                "or YAML mapping."
            )

        enabled = merged.pop("enabled", True)
        if not isinstance(enabled, bool):
            raise EmbeddingModelTrainingError(
                f"embedding_classifiers.{model_name}.enabled must be Boolean."
            )

        if model_name == MODEL_NEURAL_NETWORK:
            hidden_layers = merged.get("hidden_layer_sizes")
            if isinstance(hidden_layers, list):
                merged["hidden_layer_sizes"] = tuple(hidden_layers)

        resolved.append(
            ModelSettings(
                model_name=model_name,
                enabled=enabled,
                parameters=merged,
            )
        )

    if not any(setting.enabled for setting in resolved):
        raise EmbeddingModelTrainingError(
            "At least one embedding classifier must be enabled."
        )

    return resolved


