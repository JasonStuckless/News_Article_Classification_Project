def load_config(config_path: Path) -> dict[str, Any]:
    """Load the project configuration."""
    if not config_path.exists():
        raise SemanticNeighborAnalysisError(
            f"Configuration file not found: {config_path}"
        )

    try:
        with config_path.open("r", encoding="utf-8") as file:
            config = yaml.safe_load(file)
    except yaml.YAMLError as error:
        raise SemanticNeighborAnalysisError(
            f"Could not parse the configuration file: {error}"
        ) from error

    if not isinstance(config, dict):
        raise SemanticNeighborAnalysisError(
            "The configuration file must contain a YAML mapping."
        )

    dataset_config = config.get("dataset")
    if not isinstance(dataset_config, dict):
        raise SemanticNeighborAnalysisError(
            "The configuration must contain a 'dataset' section."
        )

    required_settings = {"train_file", "llm_train_file"}
    missing_settings = required_settings - set(dataset_config)
    if missing_settings:
        missing = ", ".join(sorted(missing_settings))
        raise SemanticNeighborAnalysisError(
            f"Missing dataset settings in config.yaml: {missing}"
        )

    return config


def resolve_project_path(configured_path: str) -> Path:
    """Resolve a configured path relative to the project root."""
    path = Path(configured_path)
    return path if path.is_absolute() else PROJECT_ROOT / path


def get_neighbor_settings(config: dict[str, Any]) -> NeighborSettings:
    """Resolve optional settings while retaining notebook-compatible defaults."""
    raw_settings = config.get("semantic_neighbors", {})
    if raw_settings is None:
        raw_settings = {}
    if not isinstance(raw_settings, dict):
        raise SemanticNeighborAnalysisError(
            "semantic_neighbors must be a YAML mapping when provided."
        )

    neighbor_count = raw_settings.get(
        "neighbor_count", DEFAULT_NEIGHBOR_COUNT
    )
    n_jobs = raw_settings.get("n_jobs", DEFAULT_N_JOBS)
    figure_dpi = raw_settings.get("figure_dpi", DEFAULT_FIGURE_DPI)
    top_classes = raw_settings.get("top_classes", DEFAULT_TOP_CLASSES)

    if not isinstance(neighbor_count, int) or neighbor_count < 1:
        raise SemanticNeighborAnalysisError(
            "semantic_neighbors.neighbor_count must be a positive integer."
        )
    if not isinstance(n_jobs, int) or n_jobs == 0:
        raise SemanticNeighborAnalysisError(
            "semantic_neighbors.n_jobs must be a non-zero integer."
        )
    if not isinstance(figure_dpi, int) or figure_dpi < 72:
        raise SemanticNeighborAnalysisError(
            "semantic_neighbors.figure_dpi must be an integer of at least 72."
        )
    if not isinstance(top_classes, int) or top_classes < 1:
        raise SemanticNeighborAnalysisError(
            "semantic_neighbors.top_classes must be a positive integer."
        )

    return NeighborSettings(
        neighbor_count=neighbor_count,
        n_jobs=n_jobs,
        figure_dpi=figure_dpi,
        top_classes=top_classes,
    )


